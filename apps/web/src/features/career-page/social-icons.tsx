export const SOCIAL_PLATFORM_NAMES = Object.keys(SOCIAL_ICONS) as SocialPlatform[];

export function socialLabel(platform: SocialPlatform): string {
  return SOCIAL_ICONS[platform]?.label ?? platform;
}

/**
 * Renders a brand mark by platform. `createElement` (not JSX) keeps the React
 * Compiler lint from reading this as deriving a component during render.
 */
export function SocialIcon({
  platform,
  className,
  style,
}: {
  platform: SocialPlatform;
  className?: string;
  style?: React.CSSProperties;
}) {
  const meta = SOCIAL_ICONS[platform];
  if (!meta) return null;
  return createElement(
    "svg",
    {
      className,
      style,
      viewBox: "0 0 24 24",
      width: "1em",
      height: "1em",
      fill: "currentColor",
      "aria-hidden": true,
      focusable: false,
    },
    createElement("path", { d: meta.path }),
  );
}
